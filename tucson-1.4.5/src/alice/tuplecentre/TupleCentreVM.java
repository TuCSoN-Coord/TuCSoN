    /**
     * Sends an out message to the tuple centre virtual machine
     * (the out puts a tuple in tuple centre)
     *
     * @param t the tuple argument of the out operation
     * @param aid the identifier of the agent invoking the operation
     * @param receiver the target receiver of output event generated by
     *        the virtual machine
     * @return the communication event generated by the invocation
     */
    public synchronized InputEvent out(Tuple t,AgentId aid,OutputEventListener receiver){
        InputEvent_out ev=new InputEvent_out(evTimeStamp++,aid,getId(),t);
        acceptEvent(ev);
        if (observers.size()>0){
        	notifyObservableEvent(ev);
        }
        return ev;
    }

    /**
     * Sends an in message to the tuple centre virtual machine
     * (the in gets a matching tuple from tuple centre)
     *
     * @param t the tuple argument of the in operation
     * @param aid the identifier of the agent invoking the operation
     * @param receiver the target receiver of output event generated by
     *        the virtual machine
     * @return the communication event generated by the invocation
     */
    public synchronized InputEvent in(TupleTemplate t,AgentId aid,OutputEventListener receiver){
        InputEvent_in ev=new InputEvent_in(evTimeStamp++,aid,getId(),t);
        synchronized (receiversMap){
        	receiversMap.put(new Long(ev.getId()),new OutputEventListenerActionInfo(ev,receiver));
        } 	
        acceptEvent(ev);
		if (observers.size()>0){
			notifyObservableEvent(ev);
		}
        return ev;
    }

