    protected void notifyInspectableEvent(InspectableEvent e){
        Iterator it=inspectors.iterator();
        System.out.println("onInspectableEvent");
        while (it.hasNext()){
            try {
                ((InspectableEventListener)it.next()).onInspectableEvent(e);
            } catch (Exception ex){
                ex.printStackTrace();
                it.remove();
            }
        }
    }

