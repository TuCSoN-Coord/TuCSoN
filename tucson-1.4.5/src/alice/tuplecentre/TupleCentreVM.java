    /**
     * blocks the VM thread of control, waiting for events incoming
     */
    protected void waitEvents(){
        try {
            if (inspectors.size()>0){
                notifyInspectableEvent(new InspectableEvent(this,InspectableEvent.TYPE_NEWSTATE));
            }

			synchronized (trapEventQueue){
				if (inputEvents.size()==0){
					busy=false;
					trapEventQueue.notifyAll();
					if (isSpy){
						spy("WAIT");
						spyState();
					}
					trapEventQueue.wait();
				}
				busy=true;
			}

            if (isSpy){
                spy("[core ] AWAKED]");
                spyState();
            }
        } catch (InterruptedException ex){
        }
    }

    /**
     * Dispatches output events to receivers,
     * making the output event set (OE) empty.
     */
    protected void notifyOutputEvents(){
        Iterator l=getOutputEventSetIterator();
        while (l.hasNext()){
            OutputEvent ev=(OutputEvent)l.next();
            if (isSpy()){
    	        spy("notifying event "+ev+"...");
            }
            if (ev.getId()!=-1){
                Long eid=new Long(ev.getId());
                synchronized (receiversMap){
	                OutputEventListenerActionInfo receiverInfo=(OutputEventListenerActionInfo)receiversMap.get(eid);
	                if (receiverInfo!=null){
	                    try {
	                        receiverInfo.receiver.notify(ev);
	                    } catch (Exception ex){
	                    	ex.printStackTrace();
	                    }
	                    // added 020629 -----------------------------
	                    //if (!receiverInfo.persistent){
	                    receiversMap.remove(eid);
	                    //}
	                    //-------------------------------------------
	                    if (isSpy){
	                        spy("notify event "+ev+" OK");
	                    }
	                } else {
	                	if (isSpy){
	                		spy("notifying event "+ev+" ... failed (unknown receiver)");
	                	}
	                }
                }
            } else {
                notifyUnknownOutputEvent(ev);
            }
            
			if (observers.size()>0){
				notifyObservableEvent(ev);
			}
            
            l.remove();
        }
    }

    /**
     * Specifies tuple centre behaviour when the VM notifies
     * an output event that is not among the basic output events
     * provided by the VM core.  Typically, they are events related
     * to specific instance of the tuple centre model.
     */
    protected abstract void   notifyUnknownOutputEvent(OutputEvent ev);


    /**
     * VM listening-reacting-speaking behaviour
     */
    public void run(){
        ready = true;
        Thread me = Thread.currentThread();
        while (!me.isInterrupted()){
            //spy("[core ] before waitEvents");
            //spyState();
            waitEvents();

            if (me.isInterrupted()){
                break;
            }

            boolean pendingOperations=true;
            while (pendingOperations){

				//-check Traps----
				TrapEvent tev = this.removeTrapEvent();
				if (tev!=null){
					fetchTriggeredReactions(tev);
				}		
				//----------------
				
                // check for reaction transition
                TriggeredReaction z=removeTriggeredReaction();
                if (z!=null){
                	updateTime();
                    evalReaction(z);
                    if (!isOutputEventSetEmpty()){
                        try {
                            notifyOutputEvents();
                        } catch(Exception ex){
                        }
                    }                    
                } else {
                    // check for speaking transition

                    // check for satisfiable query
                    Iterator it=getPendingQuerySetIterator();
                    PendingQueryEvent    ev=null;
                    OutputEvent          out_ev=null;
                    boolean found=false;
                    while (it.hasNext()){
                        ev=(PendingQueryEvent)(it.next());
                        out_ev=ev.speak_action(this);
                        if (out_ev!=null){
                            found=true;
                            // added 020624 ------------
                            //if (!ev.isPersistent()){
                            it.remove();
                            //}
                            // -------------------------
                            break;
                        }
                    }

                    if (found){
                        if (isSpy){
                            spy("speaking Ws "+ev);
                        }
                        addOutputEvent(out_ev);
                        /* fetch the reactions triggered by the event*/
                        fetchTriggeredReactions(out_ev);
                    } else {

                    	  InputEvent evi = null;
                    	  //synchronized (inputEvents){
                    	  synchronized (trapEventQueue){
                    		  // check for listening transition
                    		  if (!inputEvents.isEmpty()){
                    			  evi=(InputEvent)inputEvents.removeFirst();
                    		  }
                    	  }                    		 
                    	  if (evi!=null){
                            evi.listen_action(this);
                            if (isSpy){
                                spy("listening ..."+evi);
                            }
                            fetchTriggeredReactions(evi);
                        } else {
                            pendingOperations=false;
                        }
                    }
                }
            }
            
            try {
                notifyOutputEvents();
            } catch(Exception ex){
            	ex.printStackTrace();
            }
            
        }
    }

	public boolean isReady(){
		return ready;
	}


