    //-------------------------------------------------------------------------

    /**
     * Accepts a communication event
     *
     * It is the input service of the tuple centre machine, the only way
     * to make the virtual machine aware of an external event to be
     * processed. The event is placed in the satisfiable list or
     * notSatisfiable list, according to the current tuple space state
     * This service is executed concurrently to the thread of control
     * of the tuple centre virtual machine, so it requires synchronization.
     *
     * @param ev the input (communication) event
     */
    public void acceptEvent(InputEvent ev){
		if (isSpy){
			spy("accepting event "+ev);
		}
		
		synchronized (trapEventQueue){

			//synchronized(inputEvents){
				inputEvents.add(ev);
			//}
			
			if (!busy){
				trapEventQueue.notifyAll();
			}
        }
		if (isSpy){
			spy("accepted event "+ev);
		}
    }

	//----------
	
	/**
	 * Accepts a trap event
	 *
	 * @param ev the trap event
	 */
	protected void acceptTrapEvent(TrapEvent ev){
		try {
			if (isSpy){
				spy("accepting trap event "+ev);
			}
			synchronized (trapEventQueue){
				trapEventQueue.addLast(ev);
				if (!busy){
					trapEventQueue.notifyAll();
				}
			}
		} catch (Exception ex){
			ex.printStackTrace();
		}
		if (isSpy){
			spy("accepted trap event "+ev);
		}
	}
	
	/**
	 * Get trap Event
	 * 
	 * @return
	 */
	protected TrapEvent removeTrapEvent(){
		try {
			synchronized (trapEventQueue){
				if (trapEventQueue.isEmpty()){
					return null;
				} else {
					return (TrapEvent)trapEventQueue.removeFirst();
				}
			}
		} catch (Exception ex){
			ex.printStackTrace();
		}
		return null;
	}
		
