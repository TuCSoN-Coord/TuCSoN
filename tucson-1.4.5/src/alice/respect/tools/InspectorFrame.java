	public void onContextEvent(InspectorContextEvent msg){
		if (msg.tuples!=null){
			TupleViewer viewer=getTupleForm();
			viewer.update(msg.vmTime,msg.tuples);			

		}
		if (msg.wnEvents!=null){
			EventViewer viewer=getQueryForm();
			viewer.update(msg.vmTime,msg.wnEvents);
		}

		if (msg.reactionOk!=null){
			ReactionViewer viewer=getReactionForm();
			TriggeredReaction tr=msg.reactionOk;
			viewer.logSuccessfulReaction(msg.vmTime,tr);

		} else if (msg.reactionFailed!=null){
			ReactionViewer viewer=getReactionForm();
			TriggeredReaction tr=msg.reactionFailed;
			viewer.logFailedReaction(msg.vmTime,tr);
		}
	}






