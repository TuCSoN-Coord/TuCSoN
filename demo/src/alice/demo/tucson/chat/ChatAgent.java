    /** Creates new form GUI */
    public ChatAgent(String name,String host,TupleCentreId idMailbox) throws Exception {

        // ask for a context
        myId=new AgentId("user('"+name+"')");
        myName=new TupleArgument(myId.toTerm());

        context=Tucson.enterContext(new DefaultContextDescription(myId));

        chatId = new TupleCentreId("chat_room @ '"+host+"'");
        TupleArgument   mailBox = new TupleArgument(idMailbox.toTerm());

        // ask to enter the chat
        LogicTuple res=context.inp(chatId,new LogicTuple("join",
                                            new TupleArgument(myId.toTerm()),
                                            mailBox));
        if (res==null){
            // enter failed
            System.err.println("Name "+name+" already used.");
            System.exit(-1);
        }

        initComponents ();
        pack ();
        setTitle("CHAT user: "+name+" at "+host);
        setSize(360,400);

        new Observer(output,myId,idMailbox).start();
    }

