    class Observer extends Thread {

        private javax.swing.JTextArea output;
        private TucsonContext context;
        private TupleCentreId myTC;

        public Observer(javax.swing.JTextArea output, AgentId aid, TupleCentreId id) throws Exception {
            this.output=output;
            this.myTC=id;
            context = Tucson.enterContext(new DefaultContextDescription(aid));
        }

        public void run(){
            try {
                while (true) {
                    LogicTuple msg=context.in(myTC,new LogicTuple("msg",
                                    new Var("Who"),
                                    new Var("What"),
                                    new Var("When")));
                    TupleArgument who=msg.getArg(0);
                    TupleArgument content=msg.getArg(1);
                    TupleArgument when=msg.getArg(2);

                    output.append(toFlatString(who.toString())+">  "+toFlatString(content.toString())+"\n");
                    output.setCaretPosition(output.getText().length());
                }
            } catch (Exception ex){
                ex.printStackTrace();
            }
        }

        private String toFlatString(String st){
            if (st.startsWith("'")&&st.endsWith("'")){
                return st.substring(1,st.length()-1);
            } else {
                return st;
            }
        }

    }
